"""
Year tables for the lunisolar calendars in gcalendar.py.

Each lunar year is one 17-bit integer:

  bits  3-0 : leap month number (0 = none, 1-12)
  bits 15-4 : big-month flags for months 1-12
              (bit 15 = month 1, bit 4 = month 12; 1 = 30 days, 0 = 29)
  bit  16   : big-month flag for the leap month (1 = 30 days, 0 = 29)

The tables are rows of "YEAR: info info ..." in hexadecimal, ten years to
a row.  They are generated by the scripts named with each table; don't
edit them by hand.
"""


def _years(first_year: int, rows: str) -> list[int]:
    """Parse a table's rows, checking that each row's year follows on."""
    infos: list[int] = []
    for row in rows.splitlines():
        if not row.strip():
            continue
        year, values = row.split(":")
        if int(year) != first_year + len(infos):
            raise ValueError(f"lunar year table: row {year.strip()} out of sequence")
        infos.extend(int(value, 16) for value in values.split())
    return infos


